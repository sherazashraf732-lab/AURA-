"""Generate THIRD_PARTY_LICENSES.md from what is actually installed (backend venv + web node_modules).

Run from the repo root:  backend\\.venv\\Scripts\\python.exe -I scripts\\licenses.py
Only production dependencies are listed for the web app (npm ls --omit=dev).
"""

import importlib.metadata as md
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COPYLEFT = ("GPL", "AGPL", "LGPL", "MPL", "EPL", "SSPL", "BUSL", "Elastic", "Commons Clause")


def py_rows() -> list[tuple[str, str, str]]:
    rows = []
    for d in md.distributions():
        meta = d.metadata
        lic = meta.get("License-Expression") or ""
        if not lic:
            classifiers = [c.split(" :: ")[-1] for c in meta.get_all("Classifier") or []
                           if c.startswith("License ::")]  # fmt: skip
            lic = "; ".join(classifiers) or (meta.get("License") or "UNKNOWN").splitlines()[0][:60]
        rows.append((meta["Name"], d.version, lic))
    return sorted(set(rows), key=lambda r: r[0].lower())


def npm_rows() -> list[tuple[str, str, str]]:
    web = ROOT / "apps" / "web"
    out = subprocess.run(  # noqa: S603
        ["npm.cmd" if sys.platform == "win32" else "npm", "ls", "--omit=dev", "--all", "--json"],
        cwd=web, capture_output=True, text=True, check=False,
    )  # fmt: skip
    rows: set[tuple[str, str, str]] = set()

    def walk(deps: dict) -> None:  # type: ignore[type-arg]
        for name, info in (deps or {}).items():
            pkg = web / "node_modules" / name / "package.json"
            if "version" not in info or not pkg.exists():
                continue  # optional platform package that is not installed on this machine
            meta = json.loads(pkg.read_text(encoding="utf-8"))
            lic = meta.get("license") or "; ".join(
                x.get("type", "") for x in meta.get("licenses", []) if isinstance(x, dict)
            )
            lic = str(lic or "UNKNOWN")
            rows.add((name, info.get("version", "?"), lic))
            walk(info.get("dependencies", {}))

    walk(json.loads(out.stdout or "{}").get("dependencies", {}))
    return sorted(rows, key=lambda r: r[0].lower())


def table(rows: list[tuple[str, str, str]]) -> str:
    lines = ["| Package | Version | License | Flag |", "|---|---|---|---|"]
    for n, v, lic in rows:
        flag = "review" if any(c.lower() in lic.lower() for c in COPYLEFT) or lic == "UNKNOWN" else ""
        lines.append(f"| {n} | {v} | {lic} | {flag} |")
    return "\n".join(lines)


def main() -> None:
    py, js = py_rows(), npm_rows()
    doc = f"""# Third-Party Licenses

Generated by `scripts/licenses.py` from installed packages. AURA's own code is proprietary
(all rights reserved). Each dependency below remains under its own license; license texts ship
inside each package. Rows flagged "review" are copyleft, weak-copyleft or unidentified and are
discussed in `DEPENDENCY_AUDIT.md`.

## Backend (Python, {len(py)} packages incl. dev tools)

{table(py)}

## Web app (npm production dependencies, {len(js)} packages)

{table(js)}
"""
    (ROOT / "THIRD_PARTY_LICENSES.md").write_text(doc, encoding="utf-8")
    print(f"python={len(py)} npm={len(js)}")


if __name__ == "__main__":
    main()
